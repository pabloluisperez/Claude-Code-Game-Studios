  <h1>Términos de Servicio</h1>

  <p class="opacity-70 text-sm">Última actualización: 2026-11-04 (Sprint 14, MVP v1.0)</p>

  <h2>1. Aceptación de los términos</h2>
  <p>
    Al crear una cuenta o usar Total Soccer Manager (en adelante, "el Servicio"),
    aceptas estos Términos de Servicio. Si no estás de acuerdo, no uses el Servicio.
  </p>

  <h2>2. Descripción del Servicio</h2>
  <p>
    Total Soccer Manager es un videojuego de gestión deportiva por navegador.
    Permite simular temporadas, gestionar plantilla, finanzas y partidos. El
    Servicio se ofrece "tal cual", sin garantías de disponibilidad continua durante
    el MVP.
  </p>

  <h2>3. Cuentas y sesiones</h2>
  <p>
    Para jugar necesitas crear una cuenta con un email válido y una contraseña.
    La contraseña se almacena cifrada (argon2). Tu sesión se mantiene mediante
    una cookie HTTP-only firmada con duración de 30 días. Eres responsable de
    mantener tu contraseña en secreto.
  </p>

  <h2>4. Edad mínima</h2>
  <p>
    El Servicio está recomendado para mayores de 13 años. No contiene material
    explícito, pero las dinámicas de gestión de carrera profesional requieren
    cierta madurez.
  </p>

  <h2>5. Conducta del usuario</h2>
  <p>
    Te comprometes a no intentar explotar vulnerabilidades, alterar el estado
    del servidor, hacer ingeniería inversa del simulador, ni acceder a datos
    de otros jugadores. El simulador es server-authoritative; cualquier intento
    de modificar el estado desde el cliente es ineficaz y motivo de
    cancelación de cuenta.
  </p>

  <h2>6. Propiedad intelectual</h2>
  <p>
    El nombre del juego, el código, los datos generados procedimentalmente y
    el diseño de mecánicas son propiedad del desarrollador. Los nombres de
    clubes, jugadores y competiciones del MVP son ficticios y generados; no
    representan ligas o equipos reales.
  </p>

  <h2>7. Limitación de responsabilidad</h2>
  <p>
    El Servicio se ofrece sin garantía expresa o implícita. El desarrollador no
    se hace responsable de pérdidas de progreso por incidentes técnicos durante
    el MVP. Los backups diarios reducen el riesgo pero no son contractuales.
  </p>

  <h2>8. Suspensión y cancelación</h2>
  <p>
    Podemos suspender o cancelar tu cuenta sin previo aviso si violas estos
    Términos. Puedes solicitar la eliminación de tu cuenta enviando un correo
    al contacto indicado en la página de soporte.
  </p>

  <h2>9. Cambios en los Términos</h2>
  <p>
    Estos Términos pueden actualizarse. Cuando lo hagamos, la fecha de "última
    actualización" se modificará. El uso continuado del Servicio tras un cambio
    implica aceptación de la nueva versión.
  </p>

  <h2>10. Ley aplicable</h2>
  <p>
    Estos Términos se rigen por la legislación española. Cualquier disputa se
    resolverá en los tribunales del lugar de residencia del desarrollador,
    salvo que la ley imperativa del consumidor disponga otra cosa.
  </p>

